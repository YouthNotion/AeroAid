create type public.blood_group_type as enum ('A+','A-','B+','B-','AB+','AB-','O+','O-');

-- One row per auth user.
create table public.profiles (
  id            uuid primary key references auth.users (id) on delete cascade, -- INFERRED FK
  full_name     text,
  date_of_birth date,                     -- INFERRED type (types say string)
  blood_group   public.blood_group_type,
  area_name     text not null,            -- one of src/data/dropdown.ts `areas`
  contact       text,                     -- phone; shown to requesters
  organization  text,                     -- airline / training institute
  bio           text,
  avatar_url    text,                     -- storage path in bucket `avatars`, e.g. "<uid>/avatar.jpg"
  is_available  boolean not null default true,
  updated_at    timestamptz
);

-- A donation is both a REQUEST (status = 'pending', requester -> donor)
-- and a HISTORY entry (status = 'completed', logged by the donor).
create table public.donations (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  donor_id      uuid references public.profiles (id),
  requester_id  uuid references public.profiles (id),
  patient_name  text,
  hospital      text,
  location      text,
  reference     text,                     -- requester's name/email, or free text
  date          date,                     -- INFERRED type (types say string)
  status        text                      -- 'pending' | 'completed' (no constraint in types)
);

